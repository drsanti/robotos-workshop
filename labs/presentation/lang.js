  function translateProcedure(text) {
    if (window.LAB_LANG !== 'th') return text;
    return text.split('\n').map(line => procedureLines[line] || line).join('\n');
  }

  function view(slide) {
    if (window.LAB_LANG !== 'th') return slide;
    const th = slides[slide.id];
    if (!th) return slide;
    const copy = Object.assign({}, slide, th);
    if (th.prereq && prereq[th.prereq]) copy.prerequisites = prereq[th.prereq];
    copy.procedure = translateProcedure(slide.procedure);
    return copy;
  }

  let stored = 'en';
  try { stored = localStorage.getItem('robotos-lab-lang') === 'th' ? 'th' : 'en'; } catch { stored = 'en'; }
  window.LAB_LANG = stored;
  window.LAB_I18N = { ui, slides, view, text(key) {
    const pack = ui[window.LAB_LANG] || ui.en;
    return pack[key] || ui.en[key] || key;
  }};
  window.labPhrase = s => (window.LAB_LANG === 'th' && phrases[s]) || s;
