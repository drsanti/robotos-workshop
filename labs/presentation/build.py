"""Rebuild the offline presentation data from option A of each lab prompt."""
from pathlib import Path
import json
import re
from reading import READING

ROOT = Path(__file__).resolve().parent
LABS = ROOT.parent


def section(text, name):
    match = re.search(r"^" + re.escape(name) + r"\n(.*?)(?=\n[A-Z][A-Z /–-]+\n|\Z)", text, re.M | re.S)
    return match.group(1).strip() if match else ""


def build():
    slides = []
    for track, folder in [("mw", "mw-signal-lab"), ("wh", "wh-industrial-ice"), ("hw", "hw-dark-sci-fi")]:
        image_root = LABS / ".images" / folder
        manifest = image_root / "manifest.json"
        selected = {x["id"]: x["file"] for x in json.loads(manifest.read_text())["items"]} if manifest.exists() else {}
        for prompt in sorted((LABS / ".prompt" / track).glob("*.prompt.md")):
            text = re.search(r"```text\n(.*?)\n```", prompt.read_text(), re.S).group(1)
            field = lambda label: re.search(r"^" + label + r": (.*)$", text, re.M).group(1)
            slug = prompt.name.removesuffix(".prompt.md")
            filename = selected.get(slug, slug + ".png")
            image = image_root / filename
            evidence = section(text, "EXPECTED OBSERVATION").split("\nThese are source-based")[0]
            ident = field("Lab ID")
            reading, example, steps, flow = READING[ident.lower()]
            slides.append({
                "slug": slug, "id": ident, "track": track,
                "title": field("Title"), "objective": field("Objective"),
                "takeaway": section(text, "TAKEAWAY"), "evidence": evidence,
                "mechanism": field("Mechanism and implementation"),
                "diagramBrief": section(text, "MAIN VISUAL"),
                "prerequisites": field("Graph and prerequisites"),
                "reading": reading, "example": example, "steps": steps, "flow": flow,
                "procedure": section(text, "DEMO PROCEDURE FOR SPEAKER NOTES"),
                "cleanup": section(text, "CLEANUP"),
                "notes": [{"title": label.title(), "text": section(text, label)} for label in
                          ["DEMO PROCEDURE FOR SPEAKER NOTES", "PRACTICE AND COMPLETION", "CLEANUP", "TECHNICAL GUARDS"]],
                "source": "../" + track + "/" + slug + "/README.md",
                "prompt": "../.prompt/" + track + "/" + prompt.name,
                "background": "../.images/" + folder + "/" + filename if image.exists() else "",
            })
    assert len(slides) == 24, f"Expected 24 labs, found {len(slides)}"
    assert len(READING) == len(slides)
    (ROOT / "data.js").write_text("// Generated by build.py; edit the source prompts and rebuild.\nwindow.LAB_SLIDES = " + json.dumps(slides, ensure_ascii=False, indent=2) + ";\n")
    print(f"Built {len(slides)} slides from prompt options A.")


if __name__ == "__main__":
    build()
